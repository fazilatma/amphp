# 4-Way Multi-Store Sync Matrix Engine
def run_sync_matrix_worker(task_id: str):
    try:
        data = load_data()
        products = data.get("last_result", [])
        woo_cfg = data.get("woocommerce", {})
        bsl_cfg = data.get("basalam", {})

        total = len(products)
        matrix = []

        update_task(task_id, progress=10, step="استخراج لیست کالاهای ووکامرس و باسلام جهت تطبیق...")
        
        # Calculate matrix status for each product
        for idx, p in enumerate(products):
            if is_task_cancelled(task_id):
                update_task(task_id, status="cancelled", step="لغو شد.")
                return

            base_price = int(p.get("price") or 0)
            woo_target = apply_pricing_rules(base_price, float(woo_cfg.get("price_pct", 0)), float(woo_cfg.get("price_fixed", 0)), int(woo_cfg.get("round_to", 1000)))
            bsl_target = apply_pricing_rules(base_price, float(bsl_cfg.get("price_pct", 0)), float(bsl_cfg.get("price_fixed", 0)), int(bsl_cfg.get("round_to", 1000)))

            matrix.append({
                "index": idx,
                "title": p.get("title", ""),
                "sku": p.get("sku", ""),
                "source_price": base_price,
                "woo_target_price": woo_target,
                "basalam_target_price": bsl_target,
                "sync_status": "synced" if base_price > 0 else "price_missing",
                "stock_status": p.get("stock", "in_stock")
            })

            update_task(task_id, progress=int(10 + (idx+1)/total*80), step=f"تطبیق قیمت {idx+1}/{total}")

        with open("sync_matrix_result.json", "w", encoding="utf-8") as f:
            json.dump(matrix, f, ensure_ascii=False, indent=2)

        update_task(task_id, progress=100, status="completed", step="پایان ماتریس همگام‌سازی", result={"synced_items": len(matrix)})
    except Exception as e:
        update_task(task_id, error=str(e))

# Deployment Verification & Update Engine
def validate_deploy_source(content: bytes) -> str:
    if not content.startswith((b"#!/", b"#", b"\"\"\"", b"\'\'\'")):
        raise FetchError("فایل دانلودشده شبیه کد Python نیست")
    try:
        text = content.decode("utf-8")
    except UnicodeDecodeError:
        raise FetchError("فایل دانلودشده کدگذاری UTF-8 ندارد")

    required = ("APP_VERSION", "Flask(", '@app.get("/")', "/api/deploy/run")
    missing = [m for m in required if m not in text]
    if missing:
        raise FetchError("نسخه تازه اعتبارسنجی نشد؛ نشانه‌های Scraper4 کامل نیست: " + ", ".join(missing))

    try:
        import ast
        ast.parse(text, filename="<deploy-validate>")
    except SyntaxError as e:
        raise FetchError(f"خطای ساختاری Python در نسخه تازه: {e}")

    for line in text.splitlines():
        if line.strip().startswith("APP_VERSION"):
            parts = line.split("=", 1)
            if len(parts) == 2:
                return parts[1].strip().strip('"\'')
    return "5.0.0"

