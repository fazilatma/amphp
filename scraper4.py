# Multi-Strategy DEDUP Module
def run_dedup_engine(strategy: str = "smart") -> Dict[str, Any]:
    data = load_data()
    products = data.get("last_result", [])
    initial_count = len(products)
    if initial_count == 0:
        return {"ok": True, "initial": 0, "final": 0, "removed": 0, "groups": []}

    seen_keys = {}
    unique_products = []
    duplicate_groups = []

    for idx, p in enumerate(products):
        title = (p.get("title") or "").strip().lower()
        sku = (p.get("sku") or "").strip().lower()
        url = (p.get("url") or "").strip().lower()

        if strategy == "sku" and sku:
            key = f"sku:{sku}"
        elif strategy == "url" and url:
            key = f"url:{url}"
        elif strategy == "title":
            key = f"title:{title}"
        else:  # Smart Strategy
            norm_title = "".join(ch for ch in title if ch.isalnum())
            key = f"smart:{sku}" if sku else f"smart:{norm_title}"

        if key in seen_keys:
            orig_idx = seen_keys[key]
            duplicate_groups.append({
                "original_index": orig_idx,
                "duplicate_index": idx,
                "key": key,
                "title": p.get("title")
            })
        else:
            seen_keys[key] = idx
            unique_products.append(p)

    return {
        "ok": True,
        "initial": initial_count,
        "final": len(unique_products),
        "removed": initial_count - len(unique_products),
        "groups": duplicate_groups,
        "cleaned_products": unique_products
    }

