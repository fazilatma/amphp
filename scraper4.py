def deploy_download_source(deploy_cfg: Dict[str, Any]) -> Tuple[bytes, str, str]:
    repo = (deploy_cfg.get("repo") or DEFAULT_GITHUB_REPO).strip()
    branch = (deploy_cfg.get("branch") or DEFAULT_GITHUB_BRANCH).strip()
    path = (deploy_cfg.get("path") or DEFAULT_GITHUB_PATH).strip().lstrip("/")
    token = (deploy_cfg.get("github_token") or "").strip()
    api_url = f"https://api.github.com/repos/{repo}/contents/{path}?ref={urllib.parse.quote(branch, safe='')}"
    headers = {"Accept": "application/vnd.github.v3+json", "User-Agent": "Scraper4-Deploy/5.0.0"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    raw = fetch_url(api_url, timeout=30, headers=headers)
    meta = json.loads(raw)
    if not isinstance(meta, dict) or "content" not in meta:
        raise FetchError("پاسخ مخزن گیت‌هاب معتبر نیست")
    encoding = meta.get("encoding", "")
    if encoding == "base64":
        source_bytes = base64.b64decode("".join(meta["content"].split()))
    elif encoding in ("", "utf-8", "none"):
        source_bytes = str(meta["content"]).encode("utf-8")
    else:
        raise FetchError(f"کدگذاری محتوای گیت‌هاب ناشناخته است: {encoding}")
    remote_sha = str(meta.get("sha") or "")
    version = validate_deploy_source(source_bytes)
    return source_bytes, remote_sha, version

def deploy_install(deploy_cfg: Dict[str, Any]) -> Dict[str, Any]:
    source_bytes, remote_sha, version = deploy_download_source(deploy_cfg)
    target_path = os.path.abspath(__file__)
    if not os.path.exists(target_path):
        target_path = os.path.abspath("scraper4.py")
    try:
        current_bytes = open(target_path, "rb").read()
        current_hash = hashlib.sha256(current_bytes).hexdigest()
    except OSError:
        current_bytes = b""
        current_hash = ""
    new_hash = hashlib.sha256(source_bytes).hexdigest()
    if current_hash and current_hash == new_hash:
        return {"changed": False, "version": version, "sha": remote_sha, "message": "نسخه فعلی با آخرین نسخه مخزن یکسان است"}
    
    backup_path = f"{target_path}.{datetime.now().strftime('%Y%m%d-%H%M%S')}.bak"
    if current_bytes:
        with open(backup_path, "wb") as bf:
            bf.write(current_bytes)

    tmp_path = f"{target_path}.{os.getpid()}.tmp"
    with open(tmp_path, "wb") as tf:
        tf.write(source_bytes)
    os.replace(tmp_path, target_path)

    # Touch reload file if specified
    reload_file = deploy_cfg.get("reload_file", "").strip()
    if reload_file and os.path.exists(reload_file):
        try: os.utime(reload_file, None)
        except OSError: pass

    return {"changed": True, "version": version, "sha": remote_sha, "backup": backup_path, "message": "به‌روزرسانی با موفقیت نصب شد"}

