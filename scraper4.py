def parse_html_products(html: str, selectors: Dict[str, str], base_url: str = "") -> List[Dict[str, Any]]:
    soup = BeautifulSoup(html, "html.parser")
    container_sel = selectors.get("container", "").strip()
    if not container_sel:
        for auto_cand in [".product", ".product-item", ".c-product-box", ".product-card", "article.product", "li.product"]:
            if soup.select(auto_cand):
                container_sel = auto_cand
                break
    if not container_sel:
        container_sel = ".product, .product-item, .product-card, article"

    items = soup.select(container_sel)
    results = []
    
    title_sel = selectors.get("title", "").strip()
    price_sel = selectors.get("price", "").strip()
    image_sel = selectors.get("image", "").strip()
    url_sel = selectors.get("url", "").strip()
    sku_sel = selectors.get("sku", "").strip()

    for el in items:
        # Title
        t_el = el.select_one(title_sel) if title_sel else (el.select_one("h2, h3, .title, .product-title, .name") or el)
        title = t_el.get_text(strip=True) if t_el else ""
        if not title and el.name in ["h2", "h3", "a"]:
            title = el.get_text(strip=True)

        # Price
        p_el = el.select_one(price_sel) if price_sel else el.select_one(".price, .amount, .c-price__value, ins .amount, .product-price")
        price_raw = p_el.get_text(strip=True) if p_el else ""
        price = extract_price_numbers(price_raw)

        # Image
        img_el = el.select_one(image_sel) if image_sel else el.select_one("img")
        img_url = ""
        if img_el:
            img_url = img_el.get("data-src") or img_el.get("data-original") or img_el.get("src") or ""
            if img_url and base_url:
                img_url = urllib.parse.urljoin(base_url, img_url)

        # URL
        link_el = el.select_one(url_sel) if url_sel else (el if el.name == "a" else el.select_one("a[href]"))
        link_url = ""
        if link_el and link_el.has_attr("href"):
            link_url = urllib.parse.urljoin(base_url, link_el["href"])

        # SKU
        sku_el = el.select_one(sku_sel) if sku_sel else el.select_one(".sku, [data-sku], .product-sku")
        sku = sku_el.get_text(strip=True) if sku_el else (el.get("data-product-id") or el.get("data-sku") or "")

        if title or img_url or link_url:
            results.append({
                "title": title,
                "price": price,
                "price_raw": price_raw,
                "image": img_url,
                "url": link_url,
                "sku": sku,
                "stock": "in_stock",
                "description": "",
                "specs": {},
                "gallery": [],
                "variations": [],
                "scraped_at": datetime.now().isoformat()
            })
    return results

def run_scrape_worker(task_id: str, config: Dict[str, Any]):
    try:
        url = config.get("url", "").strip()
        pages = int(config.get("pages", 1))
        pag_type = config.get("pag_type", "query")
        pag_val = config.get("pag_val", "page")
        selectors = config.get("selectors", {})
        gap_ms = int(config.get("gap_ms", 350))

        all_products = []
        parsed = urllib.parse.urlparse(url)
        base_origin = f"{parsed.scheme}://{parsed.netloc}"

        for p in range(1, pages + 1):
            if is_task_cancelled(task_id):
                update_task(task_id, status="cancelled", step="توسط کاربر لغو شد.")
                return

            # Build URL for pagination
            if p == 1:
                page_url = url
            else:
                if pag_type == "query":
                    q = urllib.parse.parse_qs(parsed.query)
                    q[pag_val] = [str(p)]
                    new_q = urllib.parse.urlencode(q, doseq=True)
                    page_url = urllib.parse.urlunparse((parsed.scheme, parsed.netloc, parsed.path, parsed.params, new_q, parsed.fragment))
                else:
                    path_clean = parsed.path.rstrip("/")
                    page_url = urllib.parse.urlunparse((parsed.scheme, parsed.netloc, f"{path_clean}/{pag_val}/{p}/", parsed.params, parsed.query, parsed.fragment))

            update_task(task_id, progress=int((p-1)/pages*100), step=f"دریافت صفحه {p} از {pages}...", log_msg=f"دریافت نشانی: {page_url}")
            
            try:
                html = fetch_url(page_url)
                prods = parse_html_products(html, selectors, base_origin)
                all_products.extend(prods)
                update_task(task_id, log_msg=f"استخراج تعداد {len(prods)} محصول از صفحه {p}")
            except Exception as e:
                update_task(task_id, log_msg=f"خطا در صفحه {p}: {str(e)}")

            if p < pages and gap_ms > 0:
                time.sleep(gap_ms / 1000.0)

        # Save to DB
        data = load_data()
        data["last_result"] = all_products
        save_data(data)

        update_task(task_id, progress=100, status="completed", step="پایان استخراج", log_msg=f"مجموعاً {len(all_products)} محصول استخراج و ذخیره شد.", result={"count": len(all_products)})
    except Exception as e:
        update_task(task_id, error=str(e), step="شکست در اجرای اسکرپ")

