def check_auth() -> Optional[Response]:
    expected = os.environ.get("SCRAPER_PASSWORD", "").strip()
    if not expected:
        return None
    token = request.headers.get("X-Scraper-Auth", "").strip()
    if not token and request.authorization:
        token = request.authorization.password or ""
    if token != expected:
        return jsonify({"ok": False, "error": "دسترسی غیرمجاز (احراز هویت الزامی است)"}), 401
    return None

class FetchError(Exception):
    pass

def fetch_url(url: str, network_cfg: Optional[Dict[str, Any]] = None, timeout: int = 25, headers: Optional[Dict[str, str]] = None) -> str:
    if network_cfg is None:
        cfg = load_data()
        network_cfg = cfg.get("network", {})
    
    proxy_mode = network_cfg.get("proxy_mode", "direct")
    relay_url = network_cfg.get("relay_url", DEFAULT_CLOUDFLARE_RELAY).strip()
    direct_proxy = network_cfg.get("proxy", "").strip()
    verify_tls = network_cfg.get("verify_tls", True)
    
    req_headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8",
        "Accept-Language": "fa-IR,fa;q=0.9,en-US;q=0.8,en;q=0.7"
    }
    if headers:
        req_headers.update(headers)

    proxies = None
    target_url = url
    
    if proxy_mode == "relay" and relay_url:
        target_url = f"{relay_url.rstrip('/')}/?url={urllib.parse.quote(url, safe='')}"
    elif proxy_mode == "http" and direct_proxy:
        proxies = {"http": direct_proxy, "https": direct_proxy}

    try:
        resp = requests.get(target_url, headers=req_headers, proxies=proxies, timeout=timeout, verify=verify_tls)
        resp.raise_for_status()
        resp.encoding = resp.apparent_encoding or "utf-8"
        return resp.text
    except Exception as e:
        raise FetchError(f"خطا در دریافت نشانی {url}: {str(e)}")

# Background Task Registry Helpers
def register_task(task_type: str, title: str, total_steps: int = 100) -> str:
    task_id = f"task_{int(time.time()*1000)}_{uuid.uuid4().hex[:8]}"
    with TASKS_LOCK:
        TASKS[task_id] = {
            "id": task_id,
            "type": task_type,
            "title": title,
            "status": "running",
            "progress": 0,
            "total": total_steps,
            "step": "آغاز عملیات...",
            "logs": [],
            "result": None,
            "error": None,
            "created_at": time.time(),
            "updated_at": time.time(),
            "cancelled": False
        }
    return task_id

def update_task(task_id: str, progress: Optional[int] = None, step: Optional[str] = None, log_msg: Optional[str] = None, result: Optional[Any] = None, error: Optional[str] = None, status: Optional[str] = None):
    with TASKS_LOCK:
        if task_id not in TASKS:
            return
        t = TASKS[task_id]
        if progress is not None:
            t["progress"] = min(100, max(0, int(progress)))
        if step is not None:
            t["step"] = step
        if log_msg:
            t["logs"].append(f"[{datetime.now().strftime('%H:%M:%S')}] {log_msg}")
        if result is not None:
            t["result"] = result
        if error is not None:
            t["error"] = error
            t["status"] = "failed"
        if status is not None:
            t["status"] = status
        t["updated_at"] = time.time()

def is_task_cancelled(task_id: str) -> bool:
    with TASKS_LOCK:
        return TASKS.get(task_id, {}).get("cancelled", False)

# Price calculation engine
def apply_pricing_rules(base_price_toman: float, pct: float = 0, fixed: float = 0, round_to: int = 1000) -> int:
    if base_price_toman <= 0:
        return 0
    p = base_price_toman * (1.0 + (pct / 100.0)) + fixed
    if round_to > 1:
        p = round(p / round_to) * round_to
    return int(max(0, p))

def extract_price_numbers(val: Any) -> int:
    if isinstance(val, (int, float)):
        return int(val)
    if not val:
        return 0
    s = str(val).replace(",", "").replace("،", "").replace("تومان", "").replace("ریال", "").strip()
    digits = "".join(ch for ch in s if ch.isdigit())
    if not digits:
        return 0
    num = int(digits)
    if "ریال" in str(val) and num >= 10:
        num = num // 10
    return num

